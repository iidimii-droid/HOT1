#!/usr/bin/env python3
"""Download the generated art listed in art/manifest.json, shrink it to game
sizes, and pack it into public/img/assets.js as data URIs.

Raw downloads are cached in art/raw/ (git-ignored), so re-running only
re-encodes. Usage: python3 tools/build_assets.py
"""
import base64
import io
import json
import os
import sys
import urllib.request

from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), '..')
MANIFEST = os.path.join(ROOT, 'art', 'manifest.json')
RAW = os.path.join(ROOT, 'art', 'raw')
OUT = os.path.join(ROOT, 'public', 'img', 'assets.js')

# name prefix -> (max pixel size, webp quality, keep alpha)
SIZES = {
    'rifle': (200, 82, True), 'heavy': (200, 82, True), 'lance': (200, 82, True), 'hammer': (200, 82, True),
    'tank': (260, 82, True), 'hq': (420, 82, True), 'crater': (256, 80, True),
    'ground': (512, 78, False), 'marble': (512, 78, False),
    'ruin': (720, 78, False), 'keyart': (1600, 74, False),
}


def fetch(name, url):
    os.makedirs(RAW, exist_ok=True)
    path = os.path.join(RAW, name + '.png')
    if not os.path.exists(path):
        print('downloading', name)
        with urllib.request.urlopen(url, timeout=60) as r, open(path, 'wb') as f:
            f.write(r.read())
    return path


def encode(name, path):
    size, quality, alpha = SIZES[name.split('_')[0]]
    im = Image.open(path)
    im = im.convert('RGBA' if alpha else 'RGB')
    im.thumbnail((size, size), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, 'WEBP', quality=quality, method=6)
    return 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode()


def main():
    manifest = json.load(open(MANIFEST))
    out = {}
    for name, file in manifest['images'].items():
        out[name] = encode(name, fetch(name, manifest['base'] + file))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w') as f:
        f.write('// Generated by tools/build_assets.py from art/manifest.json. Do not edit.\n')
        f.write('window.IRONFALL_IMAGES = ' + json.dumps(out, indent=0) + ';\n')
    print(f'wrote {OUT}: {len(out)} images, {os.path.getsize(OUT) / 1024:.0f} KB')


if __name__ == '__main__':
    sys.exit(main())
